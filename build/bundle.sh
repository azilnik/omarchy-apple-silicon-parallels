#!/bin/bash
# build/bundle.sh — inline lib/tui.sh into install.sh between its marker comments.
#
# install.sh has to stay a single self-contained file: it is fetched by URL and piped
# straight to bash, so it cannot source anything. The terminal UI still lives in one place
# (lib/tui.sh, shared with the guest scripts) and is spliced in here.
#
#   build/bundle.sh          rewrite install.sh from lib/tui.sh
#   build/bundle.sh --check  exit 1 if the inlined copy has drifted (used by `make lint`)

set -euo pipefail
REPO="$(cd "$(dirname "$0")/.." && pwd)"
LIB="$REPO/lib/tui.sh"
TARGET="$REPO/install.sh"
BEGIN='# >>> BEGIN lib/tui.sh'
END='# <<< END lib/tui.sh'

[[ -r $LIB && -r $TARGET ]] || { echo "bundle: cannot read lib/tui.sh or install.sh" >&2; exit 1; }

# Marker sanity, before touching anything. Each of these was a way to silently destroy
# install.sh: a missing END marker made awk skip the entire installer body — and --check then
# certified the wreckage as "in sync" — while a duplicated BEGIN inlined the library twice.
nbegin=$(grep -cF "$BEGIN" "$TARGET" || true)
nend=$(grep -cF "$END" "$TARGET" || true)
[[ $nbegin -eq 1 && $nend -eq 1 ]] || {
  echo "bundle: install.sh needs exactly one BEGIN and one END marker (found $nbegin and $nend)" >&2
  exit 1
}

OUT=$(mktemp "${TMPDIR:-/tmp}/omarchy-bundle.XXXXXX")
trap 'rm -f "$OUT"' EXIT

awk -v lib="$LIB" -v b="$BEGIN" -v e="$END" '
  index($0, b) == 1 {
    print b " (generated by build/bundle.sh — edit lib/tui.sh, then `make bundle`)"
    while ((getline line < lib) > 0) print line
    close(lib)
    skip = 1
    next
  }
  index($0, e) == 1 { skip = 0; print; next }
  !skip { print }
' "$TARGET" > "$OUT"

# awk reads the library with getline, whose failure `set -e` cannot see (an unreadable lib
# just yields an installer with no UI in it, exit 0). Prove the result is a whole installer
# before letting it replace one.
for must in 'tui_init()' '_tui_render()' 'Omarchy for Parallels'; do
  grep -qF "$must" "$OUT" || {
    echo "bundle: generated install.sh is missing '$must' — refusing to write" >&2; exit 1; }
done
bash -n "$OUT" || { echo "bundle: generated install.sh does not parse — refusing to write" >&2; exit 1; }

if [[ ${1:-} == --check ]]; then
  if cmp -s "$OUT" "$TARGET"; then
    echo "bundle: install.sh is in sync with lib/tui.sh"
  else
    echo "bundle: install.sh is STALE — run 'make bundle'" >&2
    diff -u "$TARGET" "$OUT" | head -40 >&2 || true
    exit 1
  fi
else
  cat "$OUT" > "$TARGET"
  chmod +x "$TARGET"
  echo "bundle: inlined $(wc -l < "$LIB" | tr -d ' ') lines of lib/tui.sh into install.sh"
fi
